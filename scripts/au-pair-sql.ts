/**
 * The Au pair pathway as SQL that is safe to run twice: its statuses, the
 * document types its requirements name where missing, and the requirements
 * themselves. Written the way scripts/new-pathways-sql.ts writes the 1.8.5
 * pathways.
 *
 *   npx tsx scripts/au-pair-sql.ts > deploy/au-pair-pathway.sql
 *
 * Run after the migration that adds the enum value (0089): Postgres does not
 * let a new enum value be used in the transaction that adds it, which is why
 * these rows are not in the migration. Nothing already in the database is
 * changed: a status is inserted only where its code is not there for the
 * pathway, a type only where its code is missing, and a requirement only where
 * the pathway has no row for that document. Every row is provisional until the
 * Au pair department's process guide arrives (see src/db/statuses.ts).
 */
import { createId } from "../src/lib/id";
import { DOCUMENT_TYPES, STATUS_SEED } from "../src/db/statuses";
import { AU_PAIR_REQUIREMENTS, DOCUMENTATION_TYPES, FSJ_DOCUMENT_TYPES } from "../src/db/documentation-seed";
import { AU_PAIR_PATHWAYS } from "../src/lib/pathways";

const q = (v: string | null | undefined) => (v == null ? "NULL" : `'${v.replace(/'/g, "''")}'`);
const out: string[] = [
  "-- The Au pair pathway: its statuses, the document types its requirements name,",
  "-- and the requirements. Run in psql on the VPS (or the SQL editor) after",
  "-- migration 0089 and before the code that offers the pathway goes out. Safe to",
  "-- run twice: nothing already in the database is changed. Generated by",
  "-- scripts/au-pair-sql.ts; every row is provisional until the Au pair",
  "-- department's process guide arrives.",
  "BEGIN;",
  "",
  "-- Statuses. A code already there is left exactly as it is, label and order included.",
];

for (const pathway of AU_PAIR_PATHWAYS) {
  STATUS_SEED[pathway].forEach((s, i) => {
    const cols = 'id, pathway, code, label, student_label, student_label_ml, "group", sort_order, requires_reason, is_milestone, active';
    const values = [
      q(createId()),
      q(pathway),
      q(s.code),
      q(s.label),
      q(s.studentLabel),
      q(s.studentLabelMl ?? null),
      q(s.group),
      s.sortOrder ?? (i + 1) * 10,
      s.requiresReason ? "true" : "false",
      s.isMilestone ? "true" : "false",
      "true",
    ].join(", ");
    out.push(`INSERT INTO status_definitions (${cols}) VALUES (${values}) ON CONFLICT (pathway, code) DO NOTHING;`);
  });
}

// Every type a requirement below names, so the file does not depend on the
// documentation or FSJ files having been run first.
const needed = new Set(AU_PAIR_REQUIREMENTS.map((r) => r.typeCode));
const types = [...DOCUMENT_TYPES, ...DOCUMENTATION_TYPES, ...FSJ_DOCUMENT_TYPES].filter((t) => needed.has(t.code));
const missingDefinition = [...needed].filter((code) => !types.some((t) => t.code === code));
if (missingDefinition.length) throw new Error(`No document type definition for ${missingDefinition.join(", ")}`);

out.push("", "-- Document types the requirements below name, inserted only where missing.");
for (const t of types) {
  out.push(
    `INSERT INTO document_types (code, label, label_ml, uploaded_by, sort_order) VALUES (${q(t.code)}, ${q(t.label)}, ${q(t.labelMl)}, ${q(t.uploadedBy)}, ${t.sortOrder}) ON CONFLICT (code) DO NOTHING;`,
  );
}

out.push(
  "",
  "-- Requirements. Guarded by type, source and pathway: a document is asked for once",
  "-- per pathway, and a row the team has since edited is left as it is.",
);
AU_PAIR_REQUIREMENTS.forEach((r, i) => {
  const cols = "id, stage, type_code, source, pathway, required, owed_by, validity_months, guidance, sort_order";
  const values = [
    q(createId()),
    q(r.stage),
    q(r.typeCode),
    "'ALWAYS'",
    q(r.pathway),
    r.required === false ? "false" : "true",
    q(r.owedBy ?? "STUDENT"),
    r.validityMonths ?? "NULL",
    q(r.guidance ?? null),
    6500 + (i + 1) * 10,
  ].join(", ");
  const guard = `NOT EXISTS (SELECT 1 FROM document_requirements d WHERE d.type_code = ${q(r.typeCode)} AND d.source = 'ALWAYS' AND d.pathway = ${q(r.pathway)}) AND EXISTS (SELECT 1 FROM document_types t WHERE t.code = ${q(r.typeCode)})`;
  out.push(`INSERT INTO document_requirements (${cols}) SELECT ${values} WHERE ${guard};`);
});

out.push("", "COMMIT;", "", "-- What is there now.");
out.push(
  AU_PAIR_PATHWAYS.flatMap((pw) => [
    `SELECT '${pw} statuses ' || count(*) FROM status_definitions WHERE pathway = '${pw}' AND active`,
    `SELECT '${pw} requirements ' || count(*) FROM document_requirements WHERE pathway = '${pw}' AND active`,
  ]).join("\nUNION ALL ") + ";",
  "",
);
console.log(out.join("\n"));
