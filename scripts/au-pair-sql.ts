/**
 * The written Au pair process as SQL that is safe to run twice, and safe on a
 * database that loaded the provisional Au pair list of 1.8.7.
 *
 *   npx tsx scripts/au-pair-sql.ts > deploy/au-pair-pathway.sql
 *
 * Run after the migrations that add the pathway (0089) and the process's
 * columns and event kinds (0090): Postgres does not let a new enum value be
 * used in the transaction that adds it, which is why these rows are not in a
 * migration. In one transaction it:
 * 1. inserts the statuses of the written process that are missing;
 * 2. moves each Au pair application on a provisional status the guide drops to
 *    the nearest new step, with a line in its status history (JOINED is kept
 *    with a new meaning, departed, so only a file on the provisional "Arrived"
 *    JOINED moves, to the arrival step, read by that label);
 * 3. writes the guide's wording and order onto the chain (these rows were
 *    provisional, so they are brought to the guide rather than left as they
 *    were; the closing statuses are left exactly as they are);
 * 4. retires the provisional codes no longer used: deactivated, never deleted,
 *    so old history still reads;
 * 5. inserts the document types and requirements the guide names, only where
 *    missing, and brings the two provisional requirements to the guide's
 *    wording only while they still read as 1.8.7 wrote them;
 * 6. adds the registration address to the Contacts list where missing;
 * and prints what it moved and what is there.
 */
import { createId } from "../src/lib/id";
import { DOCUMENT_TYPES, STATUS_SEED } from "../src/db/statuses";
import { AU_PAIR_DOCUMENT_TYPES, AU_PAIR_PROVISIONAL_REQUIREMENTS, AU_PAIR_REQUIREMENTS, DOCUMENTATION_TYPES, FSJ_DOCUMENT_TYPES } from "../src/db/documentation-seed";
import { AU_PAIR_CONTACT_AREA, AU_PAIR_RETIRED, AU_PAIR_STEPS, AU_PAIR_TEAM } from "../src/lib/au-pair";

const q = (v: string | null | undefined) => (v == null ? "NULL" : `'${v.replace(/'/g, "''")}'`);
const PW = "AU_PAIR";
const COMMON = new Set(["PENDING_PARTNER", "ON_HOLD_INTAKE", "DEFERRED", "CLOSED_NOT_QUALIFIED", "VISA_REJECTED", "WITHDRAWN", "CASE_CLOSED"]);
const seed = STATUS_SEED.AU_PAIR.map((s, i) => ({ ...s, order: s.sortOrder ?? (i + 1) * 10 }));
const chain = seed.filter((s) => !COMMON.has(s.code));

// Every code a step names is seeded, and nothing retired is still on a step.
const stepCodes = new Set(AU_PAIR_STEPS.flatMap((s) => s.statusCodes));
for (const c of stepCodes) if (!chain.some((s) => s.code === c)) throw new Error(`Step status ${c} is not seeded`);
for (const r of AU_PAIR_RETIRED) {
  if (!stepCodes.has(r.to)) throw new Error(`${r.code} moves to ${r.to}, which is not a step`);
  if (r.retire && stepCodes.has(r.code)) throw new Error(`${r.code} is retired but still on a step`);
}

const out: string[] = [
  "-- The written Au pair process: statuses, the move off the provisional list of",
  "-- 1.8.7, document types, requirements and the registration contact. Run in psql",
  "-- on the VPS after migrations 0089 and 0090, before the code that offers the",
  "-- Au pair tab goes out. Safe to run twice, and on a database that loaded the",
  "-- provisional list. Generated by scripts/au-pair-sql.ts.",
  "BEGIN;",
  "",
  "-- 1. Statuses of the written process, inserted where missing.",
];
const cols = 'id, pathway, code, label, student_label, student_label_ml, "group", sort_order, requires_reason, is_milestone, active';
for (const s of seed) {
  const values = [
    q(createId()),
    q(PW),
    q(s.code),
    q(s.label),
    q(s.studentLabel),
    q(s.studentLabelMl ?? null),
    q(s.group),
    s.order,
    s.requiresReason ? "true" : "false",
    s.isMilestone ? "true" : "false",
    "true",
  ].join(", ");
  out.push(`INSERT INTO status_definitions (${cols}) VALUES (${values}) ON CONFLICT (pathway, code) DO NOTHING;`);
}

out.push(
  "",
  "-- 2. Files on a provisional status the guide drops go to the nearest new step,",
  "-- each with a line in its status history (by the first super admin).",
  "CREATE TEMP TABLE au_pair_moved (application_id text, from_code text, to_code text, from_id text, to_id text) ON COMMIT DROP;",
);
for (const r of AU_PAIR_RETIRED) {
  const from = `SELECT id FROM status_definitions WHERE pathway = '${PW}' AND code = ${q(r.code)}${r.provisionalLabel ? ` AND label = ${q(r.provisionalLabel)}` : ""}`;
  const to = `SELECT id FROM status_definitions WHERE pathway = '${PW}' AND code = ${q(r.to)}`;
  out.push(
    `WITH moved AS (UPDATE applications a SET status_id = (${to}), status_changed_at = now(), updated_at = now() WHERE a.status_id IN (${from}) AND EXISTS (${to}) RETURNING a.id) INSERT INTO au_pair_moved SELECT id, ${q(r.code)}, ${q(r.to)}, (${from}), (${to}) FROM moved;`,
  );
}
out.push(
  "INSERT INTO status_history (id, application_id, from_status_id, to_status_id, reason, changed_by_id) SELECT 'aupm' || substr(md5(m.application_id || m.to_code), 1, 16), m.application_id, m.from_id, m.to_id, 'The written Au pair process replaced the provisional status list', u.id FROM au_pair_moved m CROSS JOIN LATERAL (SELECT id FROM users WHERE role = 'SUPER_ADMIN' ORDER BY created_at LIMIT 1) u ON CONFLICT (id) DO NOTHING;",
  "SELECT 'Moved ' || from_code || ' to ' || to_code || ': ' || count(*) FROM au_pair_moved GROUP BY from_code, to_code ORDER BY from_code;",
  "SELECT 'Au pair applications moved off provisional statuses: ' || count(*) FROM au_pair_moved;",
);

out.push("", "-- 3. The guide's wording and order on the chain. The closing statuses are left as they are.");
for (const s of chain) {
  out.push(
    `UPDATE status_definitions SET label = ${q(s.label)}, student_label = ${q(s.studentLabel)}, student_label_ml = ${q(s.studentLabelMl ?? null)}, "group" = ${q(s.group)}, sort_order = ${s.order}, requires_reason = ${s.requiresReason ? "true" : "false"}, is_milestone = ${s.isMilestone ? "true" : "false"}, active = true WHERE pathway = '${PW}' AND code = ${q(s.code)};`,
  );
}

out.push("", "-- 4. Provisional codes no longer used: deactivated, never deleted, and moved to the end of the list.");
for (const r of AU_PAIR_RETIRED.filter((x) => x.retire)) {
  out.push(`UPDATE status_definitions SET active = false, sort_order = sort_order + 900 WHERE pathway = '${PW}' AND code = ${q(r.code)} AND active;`);
}

// Every type a requirement names, so the file does not depend on the
// documentation, Ausbildung or FSJ files having been run first.
const needed = new Set(AU_PAIR_REQUIREMENTS.map((r) => r.typeCode));
const allTypes = [...DOCUMENT_TYPES, ...DOCUMENTATION_TYPES, ...FSJ_DOCUMENT_TYPES, ...AU_PAIR_DOCUMENT_TYPES];
const types = allTypes.filter((t) => needed.has(t.code));
const missingDefinition = [...needed].filter((code) => !types.some((t) => t.code === code));
if (missingDefinition.length) throw new Error(`No document type definition for ${missingDefinition.join(", ")}`);

out.push("", "-- 5. Document types the requirements name, inserted only where missing.");
for (const t of types) {
  out.push(
    `INSERT INTO document_types (code, label, label_ml, uploaded_by, sort_order) VALUES (${q(t.code)}, ${q(t.label)}, ${q(t.labelMl)}, ${q(t.uploadedBy)}, ${t.sortOrder}) ON CONFLICT (code) DO NOTHING;`,
  );
}

out.push("", "-- The two provisional requirements, brought to the guide only while they read as 1.8.7 wrote them.");
for (const p of AU_PAIR_PROVISIONAL_REQUIREMENTS) {
  const r = AU_PAIR_REQUIREMENTS.find((x) => x.typeCode === p.typeCode && x.stage === "PROFILE");
  if (!r) throw new Error(`No written requirement for ${p.typeCode}`);
  out.push(
    `UPDATE document_requirements SET required = ${r.required === false ? "false" : "true"}, guidance = ${q(r.guidance ?? null)} WHERE pathway = '${PW}' AND type_code = ${q(p.typeCode)} AND source = 'ALWAYS' AND required = ${p.required ? "true" : "false"} AND guidance = ${q(p.guidance)};`,
  );
}

out.push("", "-- Requirements. Guarded by type, source and pathway: a document is asked for once", "-- per pathway, and a row the team has since edited is left as it is.");
AU_PAIR_REQUIREMENTS.forEach((r, i) => {
  const rcols = "id, stage, type_code, source, pathway, required, owed_by, validity_months, guidance, sort_order";
  const values = [
    q(createId()),
    q(r.stage),
    q(r.typeCode),
    "'ALWAYS'",
    q(r.pathway),
    r.required === false ? "false" : "true",
    q(r.owedBy ?? "STUDENT"),
    r.validityMonths ?? "NULL",
    q(r.guidance ?? null),
    6500 + (i + 1) * 10,
  ].join(", ");
  const guard = `NOT EXISTS (SELECT 1 FROM document_requirements d WHERE d.type_code = ${q(r.typeCode)} AND d.source = 'ALWAYS' AND d.pathway = ${q(r.pathway)}) AND EXISTS (SELECT 1 FROM document_types t WHERE t.code = ${q(r.typeCode)})`;
  out.push(`INSERT INTO document_requirements (${rcols}) SELECT ${values} WHERE ${guard};`);
});

out.push("", "-- 6. The registration address on the Contacts list, where it is not there yet.");
for (const t of AU_PAIR_TEAM) {
  out.push(
    `INSERT INTO team_contacts (id, area, name, title, email, level, sort_order) SELECT ${q(createId())}, ${q(AU_PAIR_CONTACT_AREA)}, ${q(t.name)}, ${q(t.title)}, ${q(t.email)}, ${t.level}, ${t.sortOrder} WHERE NOT EXISTS (SELECT 1 FROM team_contacts x WHERE lower(x.email) = ${q(t.email.toLowerCase())} AND x.area = ${q(AU_PAIR_CONTACT_AREA)});`,
  );
}

out.push(
  "",
  "-- What is there now.",
  `SELECT 'AU_PAIR statuses active ' || count(*) FROM status_definitions WHERE pathway = '${PW}' AND active`,
  `UNION ALL SELECT 'AU_PAIR statuses retired ' || count(*) FROM status_definitions WHERE pathway = '${PW}' AND NOT active`,
  `UNION ALL SELECT 'AU_PAIR applications on a retired status ' || count(*) FROM applications a JOIN status_definitions s ON s.id = a.status_id WHERE s.pathway = '${PW}' AND NOT s.active`,
  `UNION ALL SELECT 'AU_PAIR requirements ' || count(*) FROM document_requirements WHERE pathway = '${PW}' AND active`,
  `UNION ALL SELECT 'Au pair contacts ' || count(*) FROM team_contacts WHERE area = ${q(AU_PAIR_CONTACT_AREA)};`,
  "",
  "COMMIT;",
  "",
);
console.log(out.join("\n"));
